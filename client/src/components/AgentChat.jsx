import { useState, useRef, useEffect } from 'react';
import { api } from '../api';
import { useProfile } from '../context/ProfileContext';
import styles from './AgentChat.module.css';

const WELCOME_MSG = {
  id: 0, role: 'bot',
  text: `👋 Hi! I'm **Granite Social Coach**, powered by IBM Granite LLM.\n\nI can help you with:\n• Social media strategy & best practices\n• Content ideas and campaign planning\n• Hashtag recommendations\n• Platform-specific tips\n• Trend and competitor analysis questions\n\nWhat would you like to explore today?`,
  source: 'system',
};

const SUGGESTIONS = [
  'What type of content gets the most engagement on Instagram?',
  'How often should I post on LinkedIn?',
  'Give me 5 content ideas for a tech brand',
  'How do I grow my Twitter/X following organically?',
  'What are the best times to post on social media?',
  'How can I improve my brand\'s sentiment score?',
];

function Message({ msg }) {
  const isBot = msg.role === 'bot';
  return (
    <div className={`${styles.msgWrap} ${isBot ? styles.botWrap : styles.userWrap}`}>
      {isBot && <div className={styles.avatar}>🤖</div>}
      <div className={`${styles.bubble} ${isBot ? styles.botBubble : styles.userBubble}`}>
        <span style={{ whiteSpace: 'pre-line' }}>{msg.text}</span>
        {msg.source && msg.source !== 'system' && (
          <div className={styles.sourceTag}>
            {msg.source === 'IBM Granite LLM' ? '🤖 IBM Granite LLM' : '⚙️ Mock Response'}
          </div>
        )}
      </div>
    </div>
  );
}

export default function AgentChat() {
  const { profile } = useProfile();
  const [messages, setMessages] = useState([WELCOME_MSG]);
  const [input, setInput] = useState('');
  const [loading, setLoading] = useState(false);
  const bottomRef = useRef(null);

  useEffect(() => { bottomRef.current?.scrollIntoView({ behavior: 'smooth' }); }, [messages, loading]);

  async function send(text) {
    const q = (text || input).trim();
    if (!q || loading) return;
    setInput('');
    setMessages(prev => [...prev, { id: Date.now(), role: 'user', text: q }]);
    setLoading(true);
    try {
      const res = await api.agentQuery(q, profile);
      setMessages(prev => [...prev, {
        id: Date.now() + 1,
        role: 'bot',
        text: res.data.answer,
        source: res.data.source,
        model: res.data.model,
      }]);
    } catch (e) {
      const errMsg = e.response?.data?.type === 'ETHICS_BLOCK'
        ? `🚫 Ethics Guardrail: ${e.response.data.error}`
        : '⚠️ Could not connect to the agent server. Please ensure the backend is running on port 3001.';
      setMessages(prev => [...prev, { id: Date.now() + 1, role: 'bot', text: errMsg, source: 'system' }]);
    }
    setLoading(false);
  }

  return (
    <div className={styles.page}>
      <div className="section-header">
        <div>
          <h2 className="section-title">🤖 AI Agent Chat</h2>
          <p className="section-sub">Ask Granite Social Coach anything about social media strategy.</p>
        </div>
      </div>

      <div className={styles.chatContainer}>
        <div className={styles.messages}>
          {messages.map(m => <Message key={m.id} msg={m} />)}
          {loading && (
            <div className={`${styles.msgWrap} ${styles.botWrap}`}>
              <div className={styles.avatar}>🤖</div>
              <div className={`${styles.bubble} ${styles.botBubble}`}>
                <div className={styles.typing}><span/><span/><span/></div>
              </div>
            </div>
          )}
          <div ref={bottomRef} />
        </div>

        {/* Suggestion chips */}
        <div className={styles.suggestions}>
          {SUGGESTIONS.map(s => (
            <button key={s} className={styles.chip} onClick={() => send(s)} disabled={loading}>{s}</button>
          ))}
        </div>

        <div className={styles.inputBar}>
          <input
            value={input}
            onChange={e => setInput(e.target.value)}
            onKeyDown={e => e.key === 'Enter' && send()}
            placeholder="Ask a social media strategy question…"
            disabled={loading}
          />
          <button className="btn btn-primary" onClick={() => send()} disabled={loading || !input.trim()}>
            Send ➤
          </button>
        </div>
      </div>

      <div className={styles.disclaimer}>
        <strong>📋 Disclaimer:</strong> Responses are AI-generated by IBM Granite LLM (or mock in demo mode).
        Always verify recommendations with a qualified social media professional before implementation.
        This agent follows HAM (Helpful, Accurate, Mindful) guidelines and will not assist with unethical requests.
      </div>
    </div>
  );
}
